    public void restringirSoloNumeros(JTextField campo) { 
        campo.addKeyListener(new KeyAdapter() { 
            @Override 
            public void keyTyped(KeyEvent e) { 
                if (!Character.isDigit(e.getKeyChar())) { 
                    e.consume(); 
                } 
            } 
        }); 
    } 
 
